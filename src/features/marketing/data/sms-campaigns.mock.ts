const carriers = ["Airtel", "Jio", "Vi", "BSNL"] as const;
const statuses = ["delivered", "delivered", "delivered", "delivered", "failed", "clicked"] as const;

function buildDeliveryLog(campaignId: string, count: number): SmsDeliveryLogEntry[] {
  return Array.from({ length: count }, (_, i) => {
    const status = statuses[i % statuses.length];
    return {
      id: `${campaignId}-log-${i}`,
      msisdn: `+91 *****${String(10000 + (i * 137) % 90000).slice(-5)}`,
      status,
      timestamp: new Date(Date.now() - i * 3600000).toISOString(),
      carrier: carriers[i % carriers.length],
      errorCode: status === "failed" ? `ERR_${100 + (i % 5)}` : undefined,
    };
  });
}

function buildTimeline() {
  return Array.from({ length: 7 }, (_, d) => ({
    hour: `Day ${d + 1}`,
    delivered: 1200 + Math.floor(Math.random() * 800),
    failed: 20 + Math.floor(Math.random() * 40),
  }));
}

